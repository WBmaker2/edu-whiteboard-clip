let en: Dictionary | null = null;
let enVersion = 0;
const enListeners = new Set<() => void>();

export function loadEnglishDictionary(): Promise<void> {
  if (en) return Promise.resolve();
  return import("./i18n.en")
    .then((module) => {
      en = module.default;
      enVersion += 1;
      enListeners.forEach((listener) => listener());
    })
    .catch(() => undefined);
}

export function subscribeEnglish(listener: () => void): () => void {
  enListeners.add(listener);
  return () => enListeners.delete(listener);
}

export function englishDictionaryVersion(): number {
  return enVersion;
}

export function translate(
  language: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  const template =
    (language === "en" ? en?.[key] : undefined) ?? ko[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}

export function hasTranslation(language: Language, key: string): boolean {
  if (language === "en" && en && key in en) return true;
  return key in ko;
}

export function localizeError(language: Language, message: string): string {
  if (message.startsWith("gemini.checkHttp|")) {
    const [, status, ...rest] = message.split("|");
    return translate(language, "gemini.checkHttp", {
      status,
      message: rest.join("|"),
    });
  }
  for (const key of ["gemini.authError", "gemini.modelError", "gemini.rateError", "gemini.apiError", "gemini.callFailed"]) {
    if (!message.startsWith(`${key}|`)) continue;
    const [, ...rest] = message.split("|");
    if (key === "gemini.authError") return translate(language, key, { status: rest[0] });
    if (key === "gemini.callFailed") return translate(language, key, { models: rest.join("|") });
    return translate(language, key, { model: rest[0], message: rest.slice(1).join("|") });
  }
  if (message.startsWith("gemini.checkNetwork|")) {
    return translate(language, "gemini.checkNetwork", {
      message: message.slice("gemini.checkNetwork|".length),
    });
  }
  return hasTranslation(language, message) ? translate(language, message) : message;
}

export function useI18n() {
  const language = useStudioStore((state) => state.language);
  useSyncExternalStore(
    subscribeEnglish,
    englishDictionaryVersion,
    englishDictionaryVersion,
  );
  useEffect(() => {
    if (language === "en" && !en) void loadEnglishDictionary();
  }, [language]);
  const t = useCallback(
    (key: string, params?: Record<string, string | number>) =>
      translate(language, key, params),
    [language],
  );
  const te = useCallback(
    (message: string) => localizeError(language, message),
    [language],
  );
  return { language, t, te };
}

export function dictionaryKeys(language: Language): string[] {
  return Object.keys((language === "en" ? en : ko) ?? {}).sort();
}
