const dictionaries: Record<Language, Dictionary> = { ko, en };

export function translate(
  language: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  const template = dictionaries[language][key] ?? ko[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}

export function useI18n() {
  const language = useStudioStore((state) => state.language);
  const t = useCallback(
    (key: string, params?: Record<string, string | number>) =>
      translate(language, key, params),
    [language],
  );
  return { language, t };
}

export function dictionaryKeys(language: Language): string[] {
  return Object.keys(dictionaries[language]).sort();
}
